import Foundation

/// One emoji in the pile.
struct EmojiItem: Hashable, Sendable, Identifiable {
    /// A stable identifier, which also labels the item's question.
    var id: String
    var glyph: String
    /// A plain-language description that the model reads.
    var description: String

    init(id: String, glyph: String, description: String) {
        self.id = id
        self.glyph = glyph
        self.description = description
    }

    /// The description without its leading article, for VoiceOver and the matching-items summary.
    var name: String {
        for article in ["a ", "an "] where description.hasPrefix(article) {
            return String(description.dropFirst(article.count))
        }
        return description
    }
}

